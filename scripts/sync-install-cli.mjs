import { readFile, writeFile } from 'node:fs/promises'

const source = await readFile(new URL('./install-cli.sh', import.meta.url), 'utf8')
const generated = '// Generated by scripts/sync-install-cli.mjs; edit scripts/install-cli.sh.\n' +
  'export const INSTALL_CLI_SCRIPT = ' + JSON.stringify(source) + '\n'
const target = new URL('../src/backend/server/install-cli-content.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== generated) {
    throw new Error('Run node scripts/sync-install-cli.mjs and commit the result')
  }
} else {
  await writeFile(target, generated)
}
